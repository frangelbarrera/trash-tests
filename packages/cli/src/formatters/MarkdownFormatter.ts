import type { OrchestratorResult } from '@trash-tests/core'

export interface MarkdownFormatContext {
  repoRoot: string
}

export class MarkdownFormatter {
  static format(result: OrchestratorResult, ctx: MarkdownFormatContext): string {
    void ctx
    const lines: string[] = []
    const critical = result.findings.filter((finding) => finding.severity === 'critical').length
    const warnings = result.findings.filter((finding) => finding.severity === 'warning').length
    const ss = result.score.subscores
    const signals = [
      { label: 'Assertion Quality', score: ss.assertionQuality },
      { label: 'Repository Branch Coverage', score: ss.branchCoverage },
      { label: 'Mutation Resistance', score: ss.mutationResistance },
      { label: 'Error-Path Coverage', score: ss.errorPathCoverage },
      { label: 'Mock Sanity', score: ss.mockSanity },
    ].filter((signal): signal is { label: string; score: number } => signal.score !== null)

    lines.push(`## Trash Tests — score: ${result.score.mtc} / 100`)
    lines.push('')
    lines.push(
      `> ${result.testsAnalyzed} tests analyzed. **${critical} critical findings** and **${warnings} warnings**.`,
    )
    lines.push('')
    if (signals.length > 0) {
      lines.push('| Signal | Score |')
      lines.push('|---|---:|')
      for (const signal of signals) {
        lines.push(`| ${signal.label} | ${signal.score} |`)
      }
      lines.push('')
    }

    if (result.findings.length > 0) {
      lines.push('### Findings')
      lines.push('')
      for (const [index, finding] of result.findings.slice(0, 5).entries()) {
        lines.push(
          `${index + 1}. **\`${finding.file}:${finding.line}\`** — \`${finding.testName}\``,
        )
        lines.push(`   ${finding.reason.split('\n')[0]}`)
        lines.push('')
      }
    } else {
      lines.push('### No weak-test findings detected')
      lines.push('')
    }

    lines.push('---')
    lines.push('')
    lines.push('*Generated by [Trash Tests](https://github.com/frangelbarrera/trash-tests).*')
    return `${lines.join('\n')}\n`
  }
}
